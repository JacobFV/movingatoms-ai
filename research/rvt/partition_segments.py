"""Byte-derived partition envelope codec for pinned Revit 2023/2024/2025 profiles.

All segments are traversed by explicit lengths. Unknown footer blobs and
semantic fields are preserved, not regenerated or claimed understood. This
codec cannot establish the validity of changed model data.
"""
from dataclasses import dataclass
import struct
import zlib

# root schema tag -> (member tag, footer tag)
PROFILES = {0x365:(0xe4e,0xe61), 0x37b:(0xe7c,0xe8f), 0x391:(0xed9,0xeee)}
MAX_INFLATED_MEMBER = 1024*1024

@dataclass(frozen=True)
class Member:
    kind: int
    count: int
    body_length: int
    sequence: int
    compressed: bytes

    def inflate(self):
        d=zlib.decompressobj(31)
        data=d.decompress(self.compressed,MAX_INFLATED_MEMBER+1)
        if len(data)>MAX_INFLATED_MEMBER: raise ValueError('member exceeds supported inflation limit')
        if not d.eof or d.unused_data or d.unconsumed_tail:
            raise ValueError('member length does not match complete gzip frame')
        return data

@dataclass(frozen=True)
class Segment:
    count: int
    guid: bytes | None
    members: tuple[Member,...]
    footer: bytes
    label: bytes

@dataclass(frozen=True)
class Partition:
    root_tag: int
    segments: tuple[Segment,...]
    trailing_zero: bool

class Cursor:
    def __init__(self,data): self.data,self.pos=data,0
    def take(self,n):
        if n<0 or self.pos+n>len(self.data): raise ValueError('truncated partition')
        out=self.data[self.pos:self.pos+n];self.pos+=n
        return out
    def fields(self,fmt): return struct.unpack(fmt,self.take(struct.calcsize(fmt)))
    def expect(self,raw):
        if self.take(len(raw))!=raw: raise ValueError('unexpected partition tag or reserved field')


def decode(raw):
    c=Cursor(raw)
    version,reserved,root,zero,count=c.fields('<IIHII')
    if (version,reserved,zero)!=(9,0,0) or root not in PROFILES:
        raise ValueError('unsupported partition profile')
    tag,footer_tag=PROFILES[root]
    segments=[];guid=None
    while True:
        members=[]
        while True:
            actual,kind,n,stored,body=c.fields('<HIIII')
            if actual!=tag: raise ValueError('unexpected member tag')
            if kind==0:
                if (n,stored,body)!=(0,0,0): raise ValueError('invalid segment terminator')
                break
            if kind not in (4,5,6,7) or stored<8:
                raise ValueError('unsupported member kind/length')
            sequence,=c.fields('<Q')
            member=Member(kind,n,body,sequence,c.take(stored-8))
            member.inflate()  # CRC/ISIZE and exact EOF, not a magic-byte scan
            c.expect(struct.pack('<HI',tag-7,stored))
            members.append(member)
        actual,n=c.fields('<HI')
        if actual!=footer_tag or n not in (0,64): raise ValueError('unsupported footer')
        footer=c.take(n)
        chars,=c.fields('<I')
        if chars not in (0,34): raise ValueError('unsupported footer label length')
        label=c.take(chars*2)
        if label not in (b'', 'Data generated by Autodesk® Revit®'.encode('utf-16le')):
            raise ValueError('unsupported footer label')
        segments.append(Segment(count,guid,tuple(members),footer,label))
        actual,marker=c.fields('<HI')
        if actual!=root: raise ValueError('unexpected segment closing tag')
        if marker==0:
            c.expect(b'\xff'*4)
            remainder=c.take(len(raw)-c.pos)
            if remainder not in (b'',b'\x00'): raise ValueError('unexpected partition suffix')
            return Partition(root,tuple(segments),bool(remainder))
        if marker!=0xffffffff: raise ValueError('unsupported continuation marker')
        actual,count,guid=c.fields('<HI16s')
        if actual!=root-1: raise ValueError('unexpected continuation tag')


def encode(partition):
    """Serialize preserved envelopes. Caller changes do NOT regenerate footer integrity."""
    if partition.root_tag not in PROFILES or not partition.segments:
        raise ValueError('unsupported/empty partition')
    root=partition.root_tag;tag,footer_tag=PROFILES[root]
    first=partition.segments[0]
    if first.guid is not None: raise ValueError('base segment cannot have a GUID')
    out=bytearray(struct.pack('<IIHII',9,0,root,0,first.count))
    for i,s in enumerate(partition.segments):
        if i:
            if s.guid is None or len(s.guid)!=16: raise ValueError('continuation requires 16-byte GUID')
            out.extend(struct.pack('<HI16s',root-1,s.count,s.guid))
        for m in s.members:
            stored=len(m.compressed)+8
            out.extend(struct.pack('<HIIIIQ',tag,m.kind,m.count,stored,m.body_length,m.sequence))
            out.extend(m.compressed)
            out.extend(struct.pack('<HI',tag-7,stored))
        out.extend(struct.pack('<HIIII',tag,0,0,0,0))
        out.extend(struct.pack('<HI',footer_tag,len(s.footer)))
        out.extend(s.footer)
        out.extend(struct.pack('<I',len(s.label)//2));out.extend(s.label)
        out.extend(struct.pack('<HI',root,0xffffffff if i+1<len(partition.segments) else 0))
    out.extend(b'\xff'*4)
    if partition.trailing_zero:out.append(0)
    encoded=bytes(out)
    # Validate caller-built structures, lengths and checksums before returning.
    if decode(encoded)!=partition: raise ValueError('partition envelope did not round trip')
    return encoded
