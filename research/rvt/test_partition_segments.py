import gzip
import struct
import unittest
import zlib
from dataclasses import replace
from partition_segments import Member,Segment,Partition,PROFILES,decode,encode

class PartitionSegmentTests(unittest.TestCase):
    def sample(self,root=0x37b,trailing=False):
        m=Member(4,1,11,101,gzip.compress(b'payload\x1f\x8b\x08inside',mtime=0))
        base=Segment(19,None,(m,),bytes(range(64)), 'Data generated by Autodesk® Revit®'.encode('utf-16le'))
        continuation=Segment(7,bytes(range(16)),(replace(m,sequence=102),),b'',b'')
        return Partition(root,(base,continuation),trailing)

    def test_all_profiles_multisegment_and_exact_roundtrip(self):
        for root in PROFILES:
            for trailing in (False,True):
                p=self.sample(root,trailing);raw=encode(p)
                self.assertEqual(decode(raw),p)
                self.assertEqual(encode(decode(raw)),raw)

    def test_every_truncation_and_suffix(self):
        raw=encode(self.sample())
        for end in range(len(raw)):
            with self.subTest(end=end),self.assertRaises((ValueError,zlib.error)):
                decode(raw[:end])
        for extra in (b'x',b'\x00\x00',b'\xff'*4):
            with self.assertRaises(ValueError):decode(raw+extra)

    def test_crc_lengths_and_unknown_tags_rejected(self):
        raw=encode(self.sample())
        for at in (8,18,20,28,44,44+len(self.sample().segments[0].members[0].compressed)-8):
            bad=bytearray(raw);bad[at]^=0x40
            with self.subTest(offset=at),self.assertRaises((ValueError,zlib.error)):
                decode(bad)

    def test_serializer_rejects_inconsistent_objects(self):
        p=self.sample()
        with self.assertRaises(ValueError):encode(replace(p,segments=()))
        with self.assertRaises(ValueError):encode(replace(p,segments=(replace(p.segments[0],guid=bytes(16)),)))
        with self.assertRaises(ValueError):encode(replace(p,segments=(replace(p.segments[0],label=b'x'),)))
        with self.assertRaises(ValueError):encode(replace(p,segments=(replace(p.segments[0],footer=b'x'),)))
